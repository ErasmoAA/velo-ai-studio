const markdownIt = require("markdown-it");

module.exports = function (eleventyConfig) {

  // ── Static passthrough copies ──────────────────────────────────────
  // Root static files
  eleventyConfig.addPassthroughCopy("index.html");
  eleventyConfig.addPassthroughCopy("studio.html");
  eleventyConfig.addPassthroughCopy("theme.css");
  eleventyConfig.addPassthroughCopy("privacy.html");
  eleventyConfig.addPassthroughCopy("tos.html");
  eleventyConfig.addPassthroughCopy("contact.html");
  eleventyConfig.addPassthroughCopy("about.html");
  eleventyConfig.addPassthroughCopy("editorial.html");
  eleventyConfig.addPassthroughCopy("sitemap.xml");
  eleventyConfig.addPassthroughCopy("robots.txt");
  eleventyConfig.addPassthroughCopy("ads.txt");
  // Images / icons at root
  eleventyConfig.addPassthroughCopy("*.png");
  eleventyConfig.addPassthroughCopy("*.ico");
  eleventyConfig.addPassthroughCopy("*.svg");
  eleventyConfig.addPassthroughCopy("*.webp");
  // Decap CMS admin panel
  eleventyConfig.addPassthroughCopy("admin");
  // Media uploads from CMS
  eleventyConfig.addPassthroughCopy("assets");
  // Existing blog HTML articles (01-10) — kept as-is, not processed
  eleventyConfig.addPassthroughCopy("blog/*.html");
  // Blog index static page
  // NOTE: blog/posts.json is NOT passed through — it is generated by
  // blog/posts-data.11ty.js which merges legacy + CMS posts automatically.

  // ── Markdown filter (renders content_es / content_en fields) ───────
  const md = markdownIt({ html: true, linkify: true, typographer: true });
  eleventyConfig.addFilter("markdown", (content) =>
    content ? md.render(String(content)) : ""
  );

  // ── Date filters ───────────────────────────────────────────────────
  // Use UTC to avoid off-by-one-day when the build host is in a negative
  // UTC offset (e.g., Americas). Eleventy parses frontmatter YAML dates as
  // Date objects at 00:00:00 UTC, and toLocaleDateString defaults to the
  // host timezone, which can shift the displayed day backwards.
  eleventyConfig.addFilter("dateEs", (date) => {
    const d = date instanceof Date ? date : new Date(date + "T12:00:00Z");
    return d.toLocaleDateString("es", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
  });
  eleventyConfig.addFilter("dateEn", (date) => {
    const d = date instanceof Date ? date : new Date(date + "T12:00:00Z");
    return d.toLocaleDateString("en", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
  });
  eleventyConfig.addFilter("isoDate", (date) => {
    const d = date instanceof Date ? date : new Date(date + "T12:00:00Z");
    return d.toISOString().split("T")[0];
  });

  // ── Related posts filters ──────────────────────────────────────────
  // Filters posts from CMS collection by same tag, excluding current slug
  eleventyConfig.addFilter("relatedCMS", (collection, currentSlug, tag, limit) => {
    return (collection || [])
      .filter(p => p.data.slug !== currentSlug && p.data.tag_es === tag)
      .slice(0, limit || 3);
  });
  // Filters legacy posts (from _data/legacyPosts.json) by same tag
  eleventyConfig.addFilter("relatedLegacy", (posts, currentSlug, tag, limit) => {
    return (posts || [])
      .filter(p => p.slug !== currentSlug && p.tag_es === tag)
      .slice(0, limit || 3);
  });

  // ── Blog post collection (CMS-created .md files) ───────────────────
  eleventyConfig.addCollection("blogPost", (api) =>
    api.getFilteredByGlob("blog/posts/*.md").sort((a, b) => {
      const na = parseInt(a.data.num || "0");
      const nb = parseInt(b.data.num || "0");
      return na - nb; // ascending by num
    })
  );

  // ── Eleventy config ────────────────────────────────────────────────
  return {
    templateFormats: ["njk", "md", "11ty.js"],
    markdownTemplateEngine: "njk",
    dir: {
      input: ".",
      output: "_site",
      includes: "_includes",
      data: "_data",
    },
  };
};
